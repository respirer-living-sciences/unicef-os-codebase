const DEFAULT_COLOR = "#808080";

export const getUnclusteredCircleColor = (paramName) => {
  if (!paramName) return DEFAULT_COLOR;

  const color = colorLookup[paramName];
  if (color) return color;

  return colorLookup[paramName.toLowerCase()] || DEFAULT_COLOR;
};

